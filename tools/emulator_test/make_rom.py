#!/usr/bin/env python3
"""Writes the host test's hand-assembled 32 KiB test ROM (see tools/host_test/host_test.c) to a file."""
import sys

CODE = bytes([
    0x21, 0x00, 0x80, 0x06, 0x08,
    0x3E, 0xAA, 0x22, 0x3E, 0xCC, 0x22, 0x05, 0x20, 0xF7,
    0x3E, 0xE4, 0xE0, 0x47,
    0x3E, 0x91, 0xE0, 0x40,
    0x3E, 0x80, 0xE0, 0x26, 0x3E, 0x77, 0xE0, 0x24, 0x3E, 0xFF, 0xE0, 0x25,
    0x3E, 0x80, 0xE0, 0x11, 0x3E, 0xF0, 0xE0, 0x12, 0x3E, 0x00, 0xE0, 0x13, 0x3E, 0x87, 0xE0, 0x14,
    0x3E, 0x0A, 0xEA, 0x00, 0x00,
    0x3E, 0x5A, 0xEA, 0x00, 0xA0,
    0x18, 0xFE,
])

rom = bytearray(0x8000)
rom[0x100:0x108] = bytes([0x00, 0xC3, 0x50, 0x01, 0xCE, 0xED, 0x66, 0x66])
rom[0x134:0x13C] = b"HOSTTEST"
rom[0x147], rom[0x148], rom[0x149] = 0x03, 0x00, 0x02
x = 0
for i in range(0x134, 0x14D):
    x = (x - rom[i] - 1) & 0xFF
rom[0x14D] = x
rom[0x150:0x150 + len(CODE)] = CODE

with open(sys.argv[1], "wb") as f:
    f.write(rom)
